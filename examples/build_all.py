"""Render every example into examples/output/ (PDF, PNG and the .tex source)
and write a gallery page (examples/output/README.md).

    python examples/build_all.py            # everything
    python examples/build_all.py mlp vae    # only examples whose name matches
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))  # use the repository's pytikz without installing it

from pytikz.cli import load_pictures  # noqa: E402

OUT = HERE / "output"
SECTIONS = [("basics", "Basics"), ("ml", "Machine learning"), ("math", "Mathematics")]


def main(filters: list[str]) -> int:
    OUT.mkdir(exist_ok=True)
    gallery = ["# pytikz example gallery", "",
               "Generated by `python examples/build_all.py`. Each image links to its PDF; "
               "the `.tex` files are the generated LaTeX.", ""]
    failures = []
    for folder, title in SECTIONS:
        scripts = sorted((HERE / folder).glob("*.py"))
        rows = []
        for script in scripts:
            if filters and not any(f in script.stem for f in filters):
                continue
            t0 = time.perf_counter()
            try:
                pictures = load_pictures(script)
                for name, pic in pictures:
                    stem = script.stem if len(pictures) == 1 else f"{script.stem}_{name}"
                    pic.save(OUT / f"{stem}.tex")
                    pic.render(OUT / f"{stem}.pdf")
                    pic.render(OUT / f"{stem}.png", dpi=200)
                    rows.append((stem, f"{folder}/{script.name}"))
                print(f"  ok    {folder}/{script.name}  ({time.perf_counter() - t0:.1f}s)")
            except Exception as err:  # noqa: BLE001 - keep going, report at the end
                failures.append(script)
                print(f"  FAIL  {folder}/{script.name}: {err}")
        if rows:
            gallery += [f"## {title}", ""]
            for stem, source in rows:
                gallery += [f"### {stem}", "", f"[![{stem}]({stem}.png)]({stem}.pdf)", "",
                            f"Source: [`{source}`](../{source}) · LaTeX: [`{stem}.tex`]({stem}.tex)", ""]
    if not filters:
        (OUT / "README.md").write_text("\n".join(gallery), encoding="utf-8")
    print(f"\n{len(failures)} failure(s)" if failures else "\nall examples rendered")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
