"""End-to-end tests that run LaTeX (skipped when pdflatex is not installed)."""

from __future__ import annotations

from pathlib import Path

import pytest

import pytikz as tz
from pytikz.cli import load_pictures, main
from pytikz.compiler import converters

pytestmark = [
    pytest.mark.latex,
    pytest.mark.skipif(not tz.latex_available(), reason="pdflatex is not installed"),
]

EXAMPLES = sorted((Path(__file__).resolve().parent.parent / "examples").glob("*/*.py"))


@pytest.fixture(autouse=True)
def fresh_cache(tmp_path, monkeypatch):
    monkeypatch.setenv("PYTIKZ_CACHE", str(tmp_path / "cache"))


def test_render_pdf_png_svg(tmp_path):
    pic = tz.Picture()
    a = pic.node("A", style="block")
    b = pic.node("B", right_of=a, style="block=Red")
    pic.arrow(a, b, label="$f$")
    pdf = pic.render(tmp_path / "x.pdf")
    assert pdf.read_bytes().startswith(b"%PDF")
    assert pic.save(tmp_path / "x.tikz").read_text(encoding="utf-8").startswith("% Generated by pytikz.")
    available = converters()
    if available["png"]:
        assert pic.render(tmp_path / "x.png", dpi=72).read_bytes().startswith(b"\x89PNG")
    if available["svg"]:
        assert b"<svg" in pic.render(tmp_path / "x.svg").read_bytes()[:500]


def test_compile_error_points_at_the_line(tmp_path):
    pic = tz.Picture()
    pic.node("x", style="this key does not exist")
    with pytest.raises(tz.TikzCompileError) as info:
        pic.render(tmp_path / "bad.pdf")
    message = str(info.value)
    assert "this key does not exist" in message
    assert ">" in message and "line" in message


def test_cli_render_and_tex(tmp_path, capsys):
    script = tmp_path / "fig.py"
    script.write_text("import pytikz as tz\npic = tz.Picture()\npic.node('hi', style='block')\n", encoding="utf-8")
    assert main(["render", str(script), "-f", "pdf,tex", "-o", str(tmp_path / "out")]) == 0
    assert (tmp_path / "out" / "fig.pdf").exists() and (tmp_path / "out" / "fig.tex").exists()
    assert main(["tex", str(script)]) == 0
    assert r"\begin{tikzpicture}" in capsys.readouterr().out


@pytest.mark.parametrize("script", EXAMPLES, ids=[f"{p.parent.name}/{p.stem}" for p in EXAMPLES])
def test_example_compiles(script, tmp_path):
    pictures = load_pictures(script)
    assert pictures, "the example creates no picture"
    for name, pic in pictures:
        out = pic.render(tmp_path / f"{name}.pdf")
        assert out.stat().st_size > 1000
